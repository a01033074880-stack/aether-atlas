// AETHER 2.3.1 randomization: Global tier property tests (JUCE-free).
// Every generated patch is judged by an independent checker (this file), and by the engine's own validate().
//   build: c++ -std=c++20 -Ilibs/aether-rand/include tests/RandGlobalTests.cpp libs/aether-rand/src/Rand.cpp libs/aether-rand/src/RandState.cpp
//   run:   RandGlobalTests [seedCount]     (default 220000 generate() calls per sweep, all sweeps together > 200k)
