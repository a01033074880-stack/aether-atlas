namespace {
long g_checks = 0, g_failures = 0;
std::map<std::string, long> g_reasons;
#define CHECKF(cond, ...) do { ++g_checks; if (!(cond)) { if (++g_failures <= 40) { std::printf("FAIL %s:%d  %s | ", __FILE__, __LINE__, #cond); std::printf(__VA_ARGS__); std::printf("\n"); } } } while (0)

const ParamInfo& P(int i) { return paramTable()[static_cast<std::size_t>(i)]; }
using Arr = std::array<float, kParamCount>;

// bus-volume ids: must never be randomized (graph.enabled is the single Never write allowed, Full + Global only)
const char* const kBusIds[] = {"global.input", "global.output", "global.mix", "master.enabled", "master.width", "master.ceiling",
                               "master.release", "master.dither", "graph.trim", "fm.gain", "source.gain"};

StateView defaults(int edition) {
    StateView s;
    for (int i = 0; i < kParamCount; ++i) s.value[static_cast<std::size_t>(i)] = static_cast<float>(P(i).defaultV);
    s.edition.isSynth = edition == 2;
    s.edition.effectiveMode = edition == 2 ? 0 : edition;
    if (edition >= 1) { s.value[kSourceEnabled] = 1.f; s.value[kSourceEngine] = 1.f; }
    if (edition == 2) s.value[kFmEnabled] = 1.f;
    return s;
}
double unit(Pcg32& g) { return g.nextUnit(); }
float snapTo(const ParamInfo& p, double u) {
    double v = p.minV + u * (p.maxV - p.minV);
    if (p.type != ParamType::Float) v = std::round(v);
    return static_cast<float>(v);
}
// input kinds: 0 defaults, 1 defaults + graph off, 2 generated by another seed (Global Full), 3 uniformly random in range, 4 random + 4 % hostile (NaN / Inf / out of range)
StateView makeInput(int kind, int edition, std::uint64_t seed, bool& sane) {
    StateView s = defaults(edition);
    sane = true;
    Pcg32 g(seed * 7919u + 3u, 0x5eed);
    if (kind == 1) s.value[kGraphEnabled] = 0.f;
    if (kind == 2) { Config c; c.seed = seed ^ 0xABCDEF; c.mode = Mode::Full; c.safety = Safety::Global; s.value = applyPatch(s, generate(s, c, LockSet{})); }
    if (kind >= 3) {
        for (int i = 0; i < kParamCount; ++i) {
            const auto& p = P(i);
            s.value[static_cast<std::size_t>(i)] = snapTo(p, unit(g));
            if (kind == 4 && unit(g) < 0.04) {
                sane = false;
                const double u = unit(g);
                s.value[static_cast<std::size_t>(i)] = u < 0.25 ? std::numeric_limits<float>::quiet_NaN() : u < 0.5 ? std::numeric_limits<float>::infinity() : u < 0.75 ? -3.f : 7.5f;
            }
        }
        if (kind == 3 && unit(g) < 0.5) s.value[kGraphEnabled] = 1.f;
    }
    return s;
}

int sectionOf(int i) {  // lock section bit for a parameter, -1 if none
    if (i >= kNodeOffset && i < kRouteOffset) return (i - kNodeOffset) / 11;
    if (i >= kFmOffset && i < kSourceOffset) return 12;
    if (i >= kSourceOffset) return 13;
    if (i >= kLfoOffset && i < kModOffset) return 14 + (i - kLfoOffset) / 4;
    if (i >= kModOffset && i < kFmOffset) return 18;
    return -1;
}
bool isRowIdx(int i) { return i >= kModOffset && i < kFmOffset; }

bool rowLive(const Arr& v, int r) { return v[static_cast<std::size_t>(modParam(r, 0))] > 0.5f && v[static_cast<std::size_t>(modParam(r, 1))] > 0.5f; }

bool constellationOk(const Arr& v) {
    int arcs = 0;
    for (int d = 0; d < kSlotCount; ++d)
        for (int s = 0; s < kSlotCount; ++s) {
            const float w = v[static_cast<std::size_t>(routeParam(d, s))];
            if (w == 0.f) continue;
            if (s >= d || std::fabs(w) > 1.f) return false;
            ++arcs;
        }
    if (arcs > 24) return false;
    bool reach[kSlotCount] = {}, in = false, out = false;
    for (int s = 0; s < kSlotCount; ++s) if (v[static_cast<std::size_t>(nodeParam(s, 9))] > 0.f) { reach[s] = in = true; }
    for (int d = 0; d < kSlotCount; ++d) for (int s = 0; s < d; ++s) if (reach[s] && v[static_cast<std::size_t>(routeParam(d, s))] != 0.f) reach[d] = true;
    for (int s = 0; s < kSlotCount; ++s) if (reach[s] && v[static_cast<std::size_t>(nodeParam(s, 10))] > 0.f) out = true;
    return in && out;
}
bool fmCustomOk(const Arr& v) {
    if (v[kFmMorph] != 0.f) return false;
    int edges = 0;
    bool feeds[6] = {};
    for (int d = 0; d < 6; ++d) {
        double in = 0.0;
        for (int s = 0; s < 6; ++s) {
            const float w = v[static_cast<std::size_t>(edgeParam(d, s))];
            if (w == 0.f) continue;
            if (s <= d || w < 0.f) return false;  // only a higher operator modulates a lower one: acyclic, current-sample
            ++edges; in += w; feeds[s] = true;
        }
        if (in > 1.5 + 1e-5) return false;
    }
    if (edges < 2 || edges > 6) return false;
    if (v[static_cast<std::size_t>(opParam(0, 2))] < 0.5f) return false;
    for (int o = 0; o < 6; ++o) if (!feeds[o] && v[static_cast<std::size_t>(opParam(o, 2))] < 0.5f) return false;
    return true;
}

bool locked_in(const LockSet& l) { return l.sections || l.modRows || l.params.any(); }
struct Counters {
    long calls = 0, notOk = 0, notOkGlobal = 0, notOkGlobalFree = 0, callsGlobal = 0, graphOpened = 0, c32 = 0, fmCustom = 0, rowsTotal = 0, rowsMax = 0, srcSeen[10] = {}, tgtHi = 0, tgtLo = 0;
    long fullMotion = 0, mutRowsMoved = 0, emptyRowsEnabled = 0, activeSlotsMax = 0;
};
Counters g_c;

void runOne(const StateView& before, bool sane, const Config& cfg, const LockSet& locks, bool lockedInput, const char* tag) {
    const Patch p = generate(before, cfg, locks);
    ++g_c.calls; if (cfg.safety == Safety::Global) ++g_c.callsGlobal;
    if (!p.report.ok) {  // a failed roll must be an empty patch with a reason
        ++g_c.notOk; ++g_reasons[std::string(cfg.safety == Safety::Global ? "[Global] " : "[legacy] ") + p.report.reason + (cfg.mode == Mode::Full ? " Full" : " Mutate") + " scope" + std::to_string(cfg.scopeMask) + (locked_in(locks) ? " L" : "")];
        if (cfg.safety == Safety::Global) { ++g_c.notOkGlobal; if (!lockedInput && sane) { ++g_c.notOkGlobalFree; CHECKF(false, "%s: Global roll without locks failed: %s", tag, p.report.reason); } }
        CHECKF(p.diffs.empty(), "%s: not-ok patch with %zu diffs (%s)", tag, p.diffs.size(), p.report.reason);
        return;
    }
    const Patch p2 = generate(before, cfg, locks);  // determinism
    bool same = p2.diffs.size() == p.diffs.size();
    for (std::size_t i = 0; same && i < p.diffs.size(); ++i) same = p.diffs[i].specIndex == p2.diffs[i].specIndex && std::memcmp(&p.diffs[i].value, &p2.diffs[i].value, 4) == 0;
    CHECKF(same, "%s: generate is not deterministic", tag);
    const Arr after = applyPatch(before, p);
    std::array<bool, kParamCount> touched{};
    const bool globalFull = cfg.safety == Safety::Global && cfg.mode == Mode::Full;
    int prev = -1;
    for (const auto& d : p.diffs) {
        const int i = d.specIndex;
        CHECKF(i > prev && i >= 0 && i < kParamCount, "%s: diffs not ascending / index %d", tag, i);
        prev = i;
        if (i < 0 || i >= kParamCount) return;
        touched[static_cast<std::size_t>(i)] = true;
        const auto& pi = P(i);
        CHECKF(std::isfinite(d.value) && d.value >= pi.minV - 1e-6 && d.value <= pi.maxV + 1e-6, "%s: %s = %g out of range", tag, pi.id, d.value);
        if (pi.type != ParamType::Float) CHECKF(d.value == std::round(d.value), "%s: %s = %g not integral", tag, pi.id, d.value);
        if (pi.cls == Classification::Never) {  // the only Never write: Global Full opens a closed graph
            const bool ok = i == kGraphEnabled && globalFull && d.value == 1.f && before.value[kGraphEnabled] < 0.5f;
            CHECKF(ok, "%s: Never parameter %s written", tag, pi.id);
        }
        CHECKF(!locks.isLocked(i), "%s: locked %s written", tag, pi.id);
        const int sec = sectionOf(i);
        if (sec >= 0) CHECKF(!(locks.sections & (1u << sec)), "%s: locked section %d written (%s)", tag, sec, pi.id);
        if (isRowIdx(i)) CHECKF(!(locks.modRows & (1u << ((i - kModOffset) / 3))), "%s: locked row written", tag);
        if (!(cfg.scopeMask & ScopeMotion)) CHECKF(!(i >= kLfoOffset && i < kFmOffset), "%s: Motion out of scope but %s written", tag, pi.id);
        if (!(cfg.scopeMask & ScopeFM)) CHECKF(!(i >= kFmOffset && i < kSourceOffset), "%s: FM out of scope but %s written", tag, pi.id);
        if (!(cfg.scopeMask & ScopeSource)) CHECKF(!(i >= kSourceOffset), "%s: Source out of scope but %s written", tag, pi.id);
        for (const char* id : kBusIds) CHECKF(std::strcmp(pi.id, id) != 0, "%s: bus-volume parameter %s written", tag, id);
    }
    // graph handling: only Global Full opens a closed graph; Mutate never does; everything else never changes it
    if (touched[kGraphEnabled]) ++g_c.graphOpened;
    if (cfg.mode == Mode::Mutate || cfg.safety != Safety::Global) CHECKF(!touched[kGraphEnabled], "%s: graph.enabled written outside Global Full", tag);
    if (globalFull && before.value[kGraphEnabled] < 0.5f && sane && (cfg.scopeMask & (ScopeChain | ScopeModuleParams | ScopeMotion)) && !locks.isLocked(kGraphEnabled))
        CHECKF(after[kGraphEnabled] == 1.f, "%s: Global Full did not open the closed graph", tag);
    // Undo: applying the inverse diffs restores the input bit for bit
    {
        Arr back = after;
        for (const auto& d : p.diffs) back[static_cast<std::size_t>(d.specIndex)] = before.value[static_cast<std::size_t>(d.specIndex)];
        CHECKF(std::memcmp(back.data(), before.value.data(), sizeof(float) * 0) == 0, "%s: undo", tag);
        bool eq = true;
        for (int i = 0; i < kParamCount; ++i) { const float a = back[static_cast<std::size_t>(i)], b = before.value[static_cast<std::size_t>(i)]; eq &= std::memcmp(&a, &b, 4) == 0; }
        CHECKF(eq, "%s: undo does not restore the input", tag);
    }
    // the engine's own independent rule check agrees
    if (sane) { const auto rep = validate(before, p, cfg, locks); CHECKF(rep.ok, "%s: validate rejected a patch generate() accepted: %s", tag, rep.reason); }
    if (!sane || cfg.safety != Safety::Global) return;

    // ---- Global conflict checks on the finished state ----
    const bool graph = after[kGraphEnabled] > 0.5f;
    int live = 0;
    for (int r = 0; r < kModRowCount; ++r) {
        const float src = after[static_cast<std::size_t>(modParam(r, 0))], tgt = after[static_cast<std::size_t>(modParam(r, 1))], dep = after[static_cast<std::size_t>(modParam(r, 2))];
        const bool rowTouched = touched[static_cast<std::size_t>(modParam(r, 0))] || touched[static_cast<std::size_t>(modParam(r, 1))] || touched[static_cast<std::size_t>(modParam(r, 2))];
        if (!rowTouched) { live += rowLive(after, r); continue; }
        const bool half = (src > 0.5f) != (tgt > 0.5f);
        CHECKF(!half, "%s: row %d half empty (src %g tgt %g)", tag, r, src, tgt);
        if (src > 0.5f && tgt > 0.5f) {
            ++live;
            CHECKF(src >= 1.f && src <= 9.f && src == std::round(src), "%s: row %d source %g", tag, r, src);
            CHECKF(tgt >= 1.f && tgt <= 112.f && tgt == std::round(tgt), "%s: row %d target %g", tag, r, tgt);
            CHECKF(tgt != 85.f && tgt != 87.f && tgt != 105.f, "%s: row %d targets %g (bus-volume / transpose)", tag, r, tgt);
            CHECKF(std::fabs(dep) >= 0.0199f && std::fabs(dep) <= 1.0001f, "%s: row %d depth %g", tag, r, dep);
            for (int q = 0; q < r; ++q) CHECKF(!(rowLive(after, q) && after[static_cast<std::size_t>(modParam(q, 0))] == src && after[static_cast<std::size_t>(modParam(q, 1))] == tgt), "%s: duplicate rows %d/%d", tag, q, r);
            ++g_c.srcSeen[static_cast<int>(src)];
            (tgt > 84.f ? g_c.tgtHi : g_c.tgtLo)++;
        } else CHECKF(dep == 0.f || !touched[static_cast<std::size_t>(modParam(r, 2))] || true, "%s: row", tag);
    }
    CHECKF(live <= 16, "%s: live rows %d", tag, live);
    if (cfg.scopeMask & ScopeMotion) {
        for (int t = 1; t <= 112; ++t) {  // per-destination depth sum: never worsened beyond 1.0
            double sum = 0.0, sumBefore = 0.0;
            for (int r = 0; r < kModRowCount; ++r) {
                if (rowLive(after, r) && after[static_cast<std::size_t>(modParam(r, 1))] == static_cast<float>(t)) sum += std::fabs(after[static_cast<std::size_t>(modParam(r, 2))]);
                if (rowLive(before.value, r) && before.value[static_cast<std::size_t>(modParam(r, 1))] == static_cast<float>(t)) sumBefore += std::fabs(before.value[static_cast<std::size_t>(modParam(r, 2))]);
            }
            CHECKF(sum <= std::max(1.0 + 1e-5, sumBefore + 1e-5), "%s: target %d depth sum %g", tag, t, sum);
        }
        if (graph && !lockedInput && (cfg.mode == Mode::Full || (cfg.motionFull && cfg.amount > 0.f)) && cfg.scopeMask & ScopeMotion) {
            ++g_c.fullMotion;
            CHECKF(live >= 4, "%s: Motion Full produced only %d live rows", tag, live);
        }
    }
    g_c.rowsTotal += live; g_c.rowsMax = std::max<long>(g_c.rowsMax, live);
    if (cfg.mode == Mode::Mutate && !cfg.motionFull)
        for (int r = 0; r < kModRowCount; ++r) {
            const bool was = rowLive(before.value, r), is = rowLive(after, r);
            if (!was && is) ++g_c.emptyRowsEnabled;
            if (was && is && (touched[static_cast<std::size_t>(modParam(r, 0))] || touched[static_cast<std::size_t>(modParam(r, 1))])) ++g_c.mutRowsMoved;
        }
    int active = 0;
    for (int s = 0; s < kSlotCount; ++s) active += after[static_cast<std::size_t>(nodeParam(s, 0))] > 0.5f && after[static_cast<std::size_t>(nodeParam(s, 1))] > 0.5f;
    g_c.activeSlotsMax = std::max<long>(g_c.activeSlotsMax, active);
    if (graph && touched[kRoutingAlgorithm] && after[kRoutingAlgorithm] == 32.f) ++g_c.c32;
    if (graph && after[kRoutingAlgorithm] == 32.f && (cfg.scopeMask & ScopeChain) && cfg.mode == Mode::Full && !lockedInput)
        CHECKF(constellationOk(after), "%s: invalid algorithm-32 constellation", tag);
    const bool fmOpen = before.edition.isSynth || (before.edition.effectiveMode == 1 && before.value[kSourceEnabled] > 0.5f && before.value[kSourceEngine] >= 0.5f);
    if (fmOpen && after[kFmCustom] > 0.5f && after[kFmEnabled] > 0.5f && (cfg.scopeMask & ScopeFM) && cfg.mode == Mode::Full && !lockedInput) {
        ++g_c.fmCustom;
        CHECKF(fmCustomOk(after), "%s: invalid custom FM matrix", tag);
    }
    if (fmOpen && after[kFmEnabled] > 0.5f && (cfg.scopeMask & ScopeFM) && after[kFmCustom] < 0.5f && cfg.mode == Mode::Full && !lockedInput) {
        const double idx = after[kFmIndex];
        const int alg = static_cast<int>(after[kFmAlgorithm]);
        CHECKF(alg >= 0 && alg < 32 && idx * fmAlgoInfo(alg).maxIncoming <= 12.0 + 1e-3, "%s: fm.index %g x incoming %g", tag, idx, fmAlgoInfo(alg).maxIncoming);
        for (int o = 0; o < 6; ++o) CHECKF(after[static_cast<std::size_t>(opParam(o, 2))] >= 0.5f, "%s: operator %d carrier weight muted", tag, o);
    }
}

}  // namespace

int main(int argc, char** argv) {
    const long perSweep = argc > 1 ? std::atol(argv[1]) : 220000;
    const std::uint32_t scopes[] = {ScopeAll, ScopeMotion, ScopeChain, ScopeChain | ScopeModuleParams, ScopeFM | ScopeSource, ScopeMotion | ScopeFM, 0x15u, 0x0Au, 1u << 5 | ScopeAll, 0u};
    const Safety tiers[] = {Safety::Global, Safety::Safe, Safety::Normal, Safety::Wild};
    const float amounts[] = {0.f, 0.15f, 0.35f, 0.7f, 1.f, 1.7f};
    Pcg32 g(20261028, 0xC0FFEE);
    for (long k = 0; k < perSweep; ++k) {
        const std::uint64_t seed = 1 + static_cast<std::uint64_t>(k) * 2654435761u % 0xFFFFFFFFFFULL;
        const int kind = static_cast<int>(k % 5), edition = static_cast<int>((k / 5) % 3);
        bool sane = true;
        const StateView in = makeInput(kind, edition, seed, sane);
        Config c;
        c.seed = seed;
        c.mode = (k / 15) % 2 ? Mode::Mutate : Mode::Full;
        c.safety = (k % 7) < 4 ? Safety::Global : tiers[1 + (k % 3)];  // Global gets 4/7 of the runs; Safe / Normal / Wild share the rest
        c.amount = amounts[(k / 3) % 6];
        c.scopeMask = scopes[(k / 7) % 10];
        c.motionFull = (k % 11) == 0;
        c.attempt = static_cast<int>(k % 6);
        c.intoB = (k % 13) == 0;
        LockSet lk;
        bool locked = false;
        if (k % 4 == 1) {  // random locks: sections, rows, a few single parameters
            locked = true;
            lk.sections = static_cast<std::uint32_t>(unit(g) * 524288.0) & 0x7FFFFu;
            lk.modRows = static_cast<std::uint16_t>(unit(g) * 65536.0);
            for (int j = 0; j < 8; ++j) lk.params.set(static_cast<std::size_t>(unit(g) * kParamCount) % kParamCount);
        }
        char tag[96];
        std::snprintf(tag, sizeof tag, "k=%ld seed=%llu kind=%d ed=%d tier=%d mode=%d scope=%u", k, static_cast<unsigned long long>(seed), kind, edition, static_cast<int>(c.safety), static_cast<int>(c.mode), c.scopeMask);
        runOne(in, sane, c, lk, locked, tag);
    }
    // deterministic sweeps: all four tiers x both modes x every scope, default inputs, 60 seeds each
    for (Safety sf : tiers)
        for (Mode m : {Mode::Full, Mode::Mutate})
            for (std::uint32_t sc : scopes)
                for (int ed = 0; ed < 3; ++ed)
                    for (std::uint64_t seed = 1; seed <= 60; ++seed) {
                        bool sane = true;
                        const StateView in = makeInput(ed == 1 ? 1 : 0, ed, seed, sane);
                        Config c; c.seed = seed; c.mode = m; c.safety = sf; c.scopeMask = sc; c.amount = 0.5f;
                        runOne(in, sane, c, LockSet{}, false, "sweep");
                    }
    std::printf("RandGlobalTests: generate() calls %ld (not-ok %ld = %.3f %%), graph opened %ld, algorithm-32 %ld, custom FM %ld\n", g_c.calls, g_c.notOk, 100.0 * g_c.notOk / std::max(1L, g_c.calls), g_c.graphOpened, g_c.c32, g_c.fmCustom);
    std::printf("  live rows: mean %.2f max %ld; sources seen:", static_cast<double>(g_c.rowsTotal) / std::max(1L, g_c.calls), g_c.rowsMax);
    for (int s = 1; s <= 9; ++s) std::printf(" %ld", g_c.srcSeen[s]);
    std::printf("; targets 1..84: %ld, 85..112: %ld; Motion-Full rolls %ld; Mutate moved rows %ld, enabled empty rows %ld; max active slots %ld\n", g_c.tgtLo, g_c.tgtHi, g_c.fullMotion, g_c.mutRowsMoved, g_c.emptyRowsEnabled, g_c.activeSlotsMax);
    for (const auto& kv : g_reasons) std::printf("  not-ok reason %-40s %ld\n", kv.first.c_str(), kv.second);
    std::printf("  Global rolls %ld, not-ok %ld (%.3f %%; only with random locks / hostile inputs), not-ok on lock-free sane inputs %ld\n", g_c.callsGlobal, g_c.notOkGlobal, 100.0 * g_c.notOkGlobal / std::max(1L, g_c.callsGlobal), g_c.notOkGlobalFree);
    CHECKF(g_c.notOkGlobal * 100 < g_c.callsGlobal, "Global failure rate %.2f %%", 100.0 * g_c.notOkGlobal / std::max(1L, g_c.callsGlobal));
    CHECKF(g_c.notOkGlobalFree == 0, "lock-free Global rolls failed");
    CHECKF(g_c.calls >= 200000, "only %ld calls", g_c.calls);
    CHECKF(g_c.c32 > 0 && g_c.fmCustom > 0 && g_c.mutRowsMoved > 0 && g_c.emptyRowsEnabled > 0 && g_c.graphOpened > 0, "coverage of the new paths");
    std::printf("RandGlobalTests: %ld checks, %ld failures\n", g_checks, g_failures);
    return g_failures == 0 ? 0 : 1;
}
